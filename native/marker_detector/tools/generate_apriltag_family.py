"""Generates the AprilTag family of the ArUco dictionary ARUCO_MIP_36h12.

Input: the code table `benchmarks/marker_detection/print/aruco_mip_36h12.json`
of the parent repository (250 markers, 6 x 6 bits, row-major with the first
bit most significant, 1 is white, one black border cell around the bits).
The printed sheets in that folder were drawn from the same table.

AprilTag decodes a quad by sampling the bit cells named by the family's
`bit_x`/`bit_y` (cell coordinates including the border: 0 and 7 are border
cells, x to the right and y down on the printed face) and assembling the
code most significant bit first. It tries the four rotations of a code word
by moving it by a quarter of its bits (`rotate90`), which is only a 90 degree
rotation of the printed face when the bit cells are ordered in four
rotationally symmetric quarters. The cell order of AprilTag's own tag36h11
family has that property, so this family reuses it and re-encodes every
ArUco code in it. The generator checks the quarter symmetry, re-encodes,
and computes the minimum Hamming distance over all codes and rotations
(must be 12).

    python3 -I generate_apriltag_family.py <aruco_mip_36h12.json> <out_dir>

Writes `<out_dir>/aruco_mip_36h12_family.c` and `.h`.
"""

import json
import sys
from pathlib import Path

SIDE = 6
BITS = SIDE * SIDE

# Cell order of tag36h11 (apriltag tag36h11.c, v3.4.5), border-inclusive coordinates.
BIT_X = [1, 2, 3, 4, 5, 2, 3, 4, 3, 6, 6, 6, 6, 6, 5, 5, 5, 4, 6, 5, 4, 3, 2, 5, 4, 3, 4, 1, 1, 1, 1, 1, 2, 2, 2, 3]
BIT_Y = [1, 1, 1, 1, 1, 2, 2, 2, 3, 1, 2, 3, 4, 5, 2, 3, 4, 3, 6, 6, 6, 6, 6, 5, 5, 5, 4, 6, 5, 4, 3, 2, 5, 4, 3, 4]


def check_quarter_symmetry():
    """Rotating the face by 90 degrees must move bit i to bit i + 9 (mod 36)."""
    position = {(x, y): i for i, (x, y) in enumerate(zip(BIT_X, BIT_Y))}
    assert len(position) == BITS, "every bit cell is used once"
    quarter = BITS // 4
    for i, (x, y) in enumerate(zip(BIT_X, BIT_Y)):
        # clockwise quarter turn of the 8 x 8 face (cells 0..7): (x, y) -> (7 - y, x)
        rotated = (7 - y, x)
        assert position[rotated] == (i + quarter) % BITS, f"bit {i} is not quarter symmetric"


def reencode(aruco_code):
    """ArUco row-major code -> AprilTag code word in the tag36h11 cell order."""
    word = 0
    for x, y in zip(BIT_X, BIT_Y):
        row, col = y - 1, x - 1
        bit = (aruco_code >> (BITS - 1 - (row * SIDE + col))) & 1
        word = (word << 1) | bit
    return word


def rotate90(word):
    """AprilTag's rotate90 for 36 bits: the code word rotated left by a quarter."""
    quarter = BITS // 4
    mask = (1 << BITS) - 1
    return ((word << quarter) | (word >> (BITS - quarter))) & mask


def minimum_distance(words):
    best = BITS
    rotations = [[w, rotate90(w), rotate90(rotate90(w)), rotate90(rotate90(rotate90(w)))] for w in words]
    for i, w in enumerate(words):
        for r in rotations[i][1:]:
            best = min(best, bin(w ^ r).count("1"))
        for j in range(i + 1, len(words)):
            for r in rotations[j]:
                best = min(best, bin(w ^ r).count("1"))
    return best


HEADER = """/* Generated by tools/generate_apriltag_family.py from
 * benchmarks/marker_detection/print/aruco_mip_36h12.json; do not edit. */
#ifndef CAPTURE3D_ARUCO_MIP_36H12_FAMILY_H
#define CAPTURE3D_ARUCO_MIP_36H12_FAMILY_H

#include "apriltag.h"

#ifdef __cplusplus
extern "C" {
#endif

/* ArUco ARUCO_MIP_36h12 (250 markers, ids as in OpenCV) as an AprilTag
 * family. One instance per detector (AprilTag keeps its decode table in it). */
apriltag_family_t* aruco_mip_36h12_create(void);
void aruco_mip_36h12_destroy(apriltag_family_t* family);

#ifdef __cplusplus
}
#endif

#endif /* CAPTURE3D_ARUCO_MIP_36H12_FAMILY_H */
"""


def source(words, distance):
    lines = [
        "/* Generated by tools/generate_apriltag_family.py from",
        " * benchmarks/marker_detection/print/aruco_mip_36h12.json; do not edit.",
        " * Code words use the cell order of tag36h11; id k is ArUco marker k. */",
        "#include <stdlib.h>",
        "#include <string.h>",
        "",
        '#include "aruco_mip_36h12_family.h"',
        "",
        f"static uint64_t codedata[{len(words)}] = {{",
    ]
    for i in range(0, len(words), 4):
        lines.append("    " + " ".join(f"0x{w:016x}UL," for w in words[i:i + 4]))
    lines += [
        "};",
        "",
        f"static const uint32_t bit_x[{BITS}] = {{{', '.join(str(v) for v in BIT_X)}}};",
        f"static const uint32_t bit_y[{BITS}] = {{{', '.join(str(v) for v in BIT_Y)}}};",
        "",
        "apriltag_family_t* aruco_mip_36h12_create(void) {",
        "  apriltag_family_t* tf = calloc(1, sizeof(apriltag_family_t));",
        "  if (tf == NULL) return NULL;",
        '  tf->name = strdup("aruco_mip_36h12");',
        f"  tf->h = {distance};",
        f"  tf->ncodes = {len(words)};",
        "  tf->codes = codedata;",
        f"  tf->nbits = {BITS};",
        f"  tf->bit_x = calloc({BITS}, sizeof(uint32_t));",
        f"  tf->bit_y = calloc({BITS}, sizeof(uint32_t));",
        "  if (tf->name == NULL || tf->bit_x == NULL || tf->bit_y == NULL) {",
        "    aruco_mip_36h12_destroy(tf);",
        "    return NULL;",
        "  }",
        "  memcpy(tf->bit_x, bit_x, sizeof bit_x);",
        "  memcpy(tf->bit_y, bit_y, sizeof bit_y);",
        "  tf->width_at_border = 8;",
        "  tf->total_width = 10;",
        "  tf->reversed_border = false;",
        "  return tf;",
        "}",
        "",
        "void aruco_mip_36h12_destroy(apriltag_family_t* tf) {",
        "  if (tf == NULL) return;",
        "  free(tf->bit_x);",
        "  free(tf->bit_y);",
        "  free(tf->name);",
        "  free(tf);",
        "}",
        "",
    ]
    return "\n".join(lines)


def main(argv):
    if len(argv) != 3:
        print(__doc__)
        return 2
    table = json.loads(Path(argv[1]).read_text())
    assert table["name"] == "ARUCO_MIP_36h12" and table["bits"] == SIDE
    assert table["bitOrder"].startswith("row-major, first bit most significant; 1 is white")
    check_quarter_symmetry()
    words = [reencode(int(code, 16)) for code in table["codes"]]
    distance = minimum_distance(words)
    assert distance == table["minimumHammingDistance"] == 12, f"minimum Hamming distance {distance}"
    out = Path(argv[2])
    (out / "aruco_mip_36h12_family.h").write_text(HEADER)
    (out / "aruco_mip_36h12_family.c").write_text(source(words, distance))
    print(f"{len(words)} codes, minimum Hamming distance {distance} over all rotations")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
